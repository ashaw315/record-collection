-- SPEC.md §4.2 and §10b: `image_type` gains `gatefold`.
--
-- WHY: §10b makes a fold-out sleeve a THIRD state on the shelf, reached by a
-- different gesture from turning the record over, because it is a different
-- physical act — front -> turn -> back is rotation, front -> open -> inner
-- spread is a hinge. The state exists only where an inner image has been
-- photographed: there is no generated stand-in, since folding a sleeve open
-- onto a panel of pressing details would invent the artwork the user opened it
-- to see. The presence of a row of this type is what makes the affordance
-- appear.
--
-- ADDITIVE, not a type replacement. Migration 0005 replaced `price_type` with
-- the create/swap/drop dance because it REMOVED a value, which Postgres cannot
-- do in place. Adding one needs none of that, and doing it that way here would
-- rewrite a column for no reason.
--
-- MEASURED, not assumed, on the Postgres 16.14 this project runs (docker
-- compose, `postgres:16-alpine`), because the received wisdom is out of date:
--
--   * `ALTER TYPE ... ADD VALUE` inside a transaction block SUCCEEDS on a
--     pre-existing type. The restriction that made this fail was lifted in
--     Postgres 12. drizzle-kit wraps each migration file in a transaction, so
--     this mattered enough to check — and it works.
--   * The new value CANNOT BE USED in the same transaction:
--     `ERROR: unsafe use of new value "d" of enum type` /
--     `HINT: New enum values must be committed before they can be used.`
--     So a migration adding the value AND backfilling rows to it would fail.
--     This one only adds the value; a later migration wanting to WRITE
--     `gatefold` rows must be a separate file.
--
-- Positioned before `label` so the enum reads in the order a sleeve is
-- examined — front, back, inside, then the detail shots. `gallery-order.ts`
-- carries the same order for the same reason.
--
-- Forward-only per CLAUDE.md §7: 0000 created the type and is never edited.
--
-- Generated by `drizzle-kit generate`, then renamed from its random tag and
-- commented. Hand-writing the file was tried first and SILENTLY DID NOTHING:
-- a journal entry alone is not enough, drizzle-kit also needs the matching
-- `meta/NNNN_snapshot.json`, and without it the migrator reports
-- "migrations applied successfully" while skipping the file. Caught by checking
-- `enum_range` afterwards rather than trusting the success message.
--
-- APPLY IT WITH THE ENV VAR SET:
--   TEST_DATABASE_URL=... npx drizzle-kit migrate
-- A bare `npx drizzle-kit migrate` does NOT load `.env.test` — it exits 1 with
-- no error on stderr, having applied nothing, which reads exactly like a broken
-- migration. `npm run db:migrate` has the same gap. Measured while writing this
-- file: the same command that "failed" against the test database succeeded
-- against an identical scratch database whose URL was passed explicitly.

ALTER TYPE "public"."image_type" ADD VALUE 'gatefold' BEFORE 'label';
