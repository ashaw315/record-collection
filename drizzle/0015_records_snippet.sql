-- SPEC.md §4.2 and §10b: `records` gains `snippet` and `snippet_edited_at`.
--
-- **These columns were specified by A4 and never built.** They have been in
-- §4.2 — with a paragraph explaining why `snippet_edited_at` is a timestamp and
-- not a boolean — since before step 13, and no migration ever created them.
-- Nothing referenced them, so nothing failed. Found while planning 13c unit 1,
-- which is the first code to need them (NOTES: "an amendment is a claim about
-- the document, not about the database").
--
-- BOTH NULLABLE, WITH NO DEFAULT, and each null means something specific:
--
--   snippet          NULL = no snippet. §10b: "Absence is fine. A record with
--                    no snippet shows none, and no placeholder invites one."
--   snippet_edited_at NULL = the text is as generated, so a regeneration may
--                    replace it freely. NON-NULL = the USER owns it, and a
--                    regeneration must refuse unless explicitly confirmed
--                    (§7.8, A31a).
--
-- A boolean `snippet_is_edited DEFAULT false` was rejected in §4.2 and the
-- reason survives here: `false` would mean both "generated" and "never asked",
-- two different facts collapsed into one value at write time.
--
-- Deleting a snippet sets `snippet` to null and LEAVES `snippet_edited_at`
-- alone (§4.2) — a deliberate deletion is an edit, and the user still owns the
-- absence.
--
-- Additive and nullable, so it is safe on a populated table: no rewrite, no
-- lock beyond the catalogue update, and every existing row stays valid. The 125
-- records in dev get NULL for both, which reads correctly as "no snippet yet".
--
-- Generated by `drizzle-kit generate` so the SQL, the snapshot and the journal
-- entry are written together. Hand-writing the file leaves the snapshot missing,
-- and `drizzle-kit migrate` then prints "migrations applied successfully" and
-- applies nothing (NOTES).

ALTER TABLE "records" ADD COLUMN "snippet" text;--> statement-breakpoint
ALTER TABLE "records" ADD COLUMN "snippet_edited_at" timestamp with time zone;